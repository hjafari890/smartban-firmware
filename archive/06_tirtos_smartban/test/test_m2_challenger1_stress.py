# SUITE 2: Monotonic 32-Bit Unsigned Rollover Boundary Verification (2^32 - 1 -> 0)
# =============================================================================
def test_32bit_rollover_stress():
    print("\n" + "="*78)
    print(" [CHALLENGE SUITE 2] MONOTONIC 32-BIT UNSIGNED ROLLOVER (2^32 - 1 -> 0)")
    print("="*78)

    rb = CModelSPSCRingBuffer(128)

    # 1. Boundary Case: Head and Tail both at 0xFFFFFFFF
    rb.head = 0xFFFFFFFF
    rb.tail = 0xFFFFFFFF
    assert rb.is_empty(), "Empty check failed at 0xFFFFFFFF"
    assert not rb.is_full(), "Full check failed at 0xFFFFFFFF"
    assert rb.available() == 0
    assert rb.free_space() == 128
    print("  [PASS] Boundary Case 1: head=tail=0xFFFFFFFF (Empty=True, Available=0, Free=128)")

    # 2. Boundary Case: Push across boundary (head transitions 0xFFFFFFFF -> 0x00000000)
    assert rb.push({"val": 42}), "Push at 0xFFFFFFFF failed"
    assert rb.head == 0x00000000, f"Head failed to wrap to 0: {rb.head:#x}"
    assert rb.tail == 0xFFFFFFFF
    assert rb.available() == 1, f"Available mismatch across boundary: {rb.available()} != 1"
    assert rb.free_space() == 127
    assert not rb.is_empty()
    assert not rb.is_full()
    print("  [PASS] Boundary Case 2: Head wrapped 0xFFFFFFFF -> 0x00000000 (Available=1, Free=127)")

    # 3. Boundary Case: Pop across boundary (tail transitions 0xFFFFFFFF -> 0x00000000)
    item = rb.pop()
    assert item is not None and item["val"] == 42
    assert rb.tail == 0x00000000, f"Tail failed to wrap to 0: {rb.tail:#x}"
    assert rb.head == 0x00000000
    assert rb.is_empty()
    assert rb.available() == 0
    assert rb.free_space() == 128
    print("  [PASS] Boundary Case 3: Tail wrapped 0xFFFFFFFF -> 0x00000000 (Empty=True, Free=128)")

    # 4. Boundary Case: Buffer exactly full spanning rollover boundary
    # tail = 0xFFFFFF80 (2^32 - 128), head = 0x00000000
    rb.tail = uint32(0xFFFFFF80)
    rb.head = uint32(0x00000000)
    assert rb.available() == 128, f"Available mismatch: {rb.available()} != 128"
    assert rb.is_full(), "Buffer must report full when head=0, tail=0xFFFFFF80"
    assert rb.free_space() == 0, f"Free space mismatch: {rb.free_space()} != 0"
    assert not rb.is_empty()
    print("  [PASS] Boundary Case 4: Spanning Full Buffer: tail=0xFFFFFF80, head=0x00000000 (Full=True, Free=0)")

    # 5. Continuous Stream Crossing Boundary: 10,000 samples across rollover
    print("  --- Continuous streaming across rollover boundary (10,000 items) ---")
    rb.reset()
    # Start 256 samples before 2^32 - 1
    rb.head = uint32(0xFFFFFF00)
    rb.tail = uint32(0xFFFFFF00)

    for i in range(10000):
        expected_head = uint32(0xFFFFFF00 + i)
        expected_tail = expected_head
        assert rb.head == expected_head, f"Head desync at {i}: {rb.head:#x} != {expected_head:#x}"
        assert rb.push({"seq": i}), f"Push failed at step {i}"
        assert rb.head == uint32(expected_head + 1)
        assert rb.available() == 1
        assert rb.free_space() == 127

        # Physical slot verification
        slot = expected_head & rb.mask
        assert rb.buffer[slot]["seq"] == i, f"Slot corruption at physical index {slot}"

        popped = rb.pop()
        assert popped is not None and popped["seq"] == i, f"Pop corrupted at step {i}"
        assert rb.tail == uint32(expected_tail + 1)
        assert rb.is_empty()

    print("  [PASS] 10,000 consecutive push/pops streamed seamlessly through 2^32-1 -> 0 transition")

    # 6. Batch Pop Spanning Boundary
    print("  --- Batch pop spanning rollover boundary ---")
    rb.reset()
    # Tail at 0xFFFFFFFC (4 slots before wrap), Head at 0x0000000C (12 slots after wrap)
    # Total available: 16 items
    rb.tail = uint32(0xFFFFFFFC)
    rb.head = uint32(0xFFFFFFFC)
    for i in range(16):
        assert rb.push({"batch_id": i})
    assert rb.head == uint32(0x0000000C), f"Head mismatch: {rb.head:#x}"
    assert rb.tail == uint32(0xFFFFFFFC)
    assert rb.available() == 16

    batch = rb.pop_batch(16)
    assert len(batch) == 16, f"Batch size mismatch: {len(batch)} != 16"
    for i in range(16):
        assert batch[i]["batch_id"] == i, f"Batch item {i} corrupted"
    assert rb.tail == uint32(0x0000000C), f"Tail failed to advance across boundary: {rb.tail:#x}"
    assert rb.is_empty()
    print("  [PASS] Batch pop of 16 items spanning physical & 32-bit wrap verified with perfect ordering")


