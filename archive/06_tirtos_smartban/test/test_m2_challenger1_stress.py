# SUITE 4: ARM Cortex-M4 Memory Barrier Disassembly Verification
# =============================================================================
def test_assembly_memory_barriers():
    print("\n" + "="*78)
    print(" [CHALLENGE SUITE 4] ARM CORTEX-M4 DMB MEMORY BARRIER DISASSEMBLY")
    print("="*78)

    obj_file = os.path.join(PROJECT_DIR, "obj", "ring_buffer.obj")
    assert os.path.exists(obj_file), f"Object file missing: {obj_file}"
    assert os.path.exists(OBJDUMP), f"tiarmobjdump missing: {OBJDUMP}"

    res = subprocess.run([OBJDUMP, "-d", obj_file], capture_output=True, text=True)
    assert res.returncode == 0, f"Disassembly failed: {res.stderr}"
    disasm = res.stdout

    # Audit Function 1: ringbuf_ecg_push
    sec_ecg_push = re.search(r'Disassembly of section \.text\.ringbuf_ecg_push:(.*?)(?:Disassembly of section|\Z)', disasm, re.DOTALL)
    assert sec_ecg_push, "ringbuf_ecg_push section not found in disassembly"
    code = sec_ecg_push.group(1)

    # In Cortex-M Thumb2, DMB instruction opcode is 'f3bf 8f5f' -> 'dmb sy'
    assert 'dmb\tsy' in code, "dmb sy instruction missing in ringbuf_ecg_push"

    # Verify order: payload store (stm.w) -> dmb sy -> head update (str.w)
    stm_pos = code.find("stm.w")
    dmb_pos = code.find("dmb\tsy")
    # Head pointer is at offset 0xc00
    head_str_pos = code.find("str.w\tr1, [r0, #0xc00]")
    assert stm_pos != -1, "stm.w payload store not found in ringbuf_ecg_push"
    assert dmb_pos != -1, "dmb sy not found in ringbuf_ecg_push"
    assert head_str_pos != -1, "Head pointer update store not found in ringbuf_ecg_push"
    assert stm_pos < dmb_pos < head_str_pos, (
        f"Strict barrier sequence violated in ringbuf_ecg_push! "
        f"stm: {stm_pos}, dmb: {dmb_pos}, head_str: {head_str_pos}"
    )
    print("  [PASS] ringbuf_ecg_push: Payload store (stm.w) -> DMB SY -> Head store (str.w [r0, #0xc00]) verified in ARM machine code")

    # Audit Function 2: ringbuf_ecg_pop
    sec_ecg_pop = re.search(r'Disassembly of section \.text\.ringbuf_ecg_pop:(.*?)(?:Disassembly of section|\Z)', disasm, re.DOTALL)
    assert sec_ecg_pop, "ringbuf_ecg_pop section not found"
    pop_code = sec_ecg_pop.group(1)

    # Should have TWO DMBs: one before read, one after read before tail update
    dmb_matches = list(re.finditer(r'dmb\tsy', pop_code))
    assert len(dmb_matches) >= 2, f"Expected at least 2 DMBs in ringbuf_ecg_pop, found {len(dmb_matches)}"
    dmb1_pos = dmb_matches[0].start()
    dmb2_pos = dmb_matches[1].start()
    ldm_pos = pop_code.find("ldm.w")
    tail_str_pos = pop_code.find("str.w\tr1, [r0, #0xc04]")

    assert dmb1_pos < ldm_pos < dmb2_pos < tail_str_pos, (
        f"Barrier ordering violated in ringbuf_ecg_pop! "
        f"dmb1: {dmb1_pos}, ldm: {ldm_pos}, dmb2: {dmb2_pos}, tail_str: {tail_str_pos}"
    )
    print("  [PASS] ringbuf_ecg_pop: DMB SY -> Payload read (ldm.w) -> DMB SY -> Tail store (str.w [r0, #0xc04]) verified in ARM machine code")

    # Audit Function 3: ringbuf_ecg_pop_batch
    sec_ecg_batch = re.search(r'Disassembly of section \.text\.ringbuf_ecg_pop_batch:(.*?)(?:Disassembly of section|\Z)', disasm, re.DOTALL)
    assert sec_ecg_batch, "ringbuf_ecg_pop_batch section not found"
    batch_code = sec_ecg_batch.group(1)
    batch_dmbs = list(re.finditer(r'dmb\tsy', batch_code))
    assert len(batch_dmbs) >= 2, f"Expected 2 DMBs in ringbuf_ecg_pop_batch, found {len(batch_dmbs)}"
    batch_tail_str = batch_code.find("str.w\tr1, [r0, #0xc04]")
    assert batch_dmbs[0].start() < batch_code.find("ldm.w") < batch_dmbs[1].start() < batch_tail_str
    print("  [PASS] ringbuf_ecg_pop_batch: DMB SY before loop and DMB SY before Tail store verified")

    # Audit Function 4: ringbuf_imu_push
    sec_imu_push = re.search(r'Disassembly of section \.text\.ringbuf_imu_push:(.*?)(?:Disassembly of section|\Z)', disasm, re.DOTALL)
    assert sec_imu_push, "ringbuf_imu_push section not found"
    imu_push_code = sec_imu_push.group(1)
    assert 'dmb\tsy' in imu_push_code
    imu_bl_pos = imu_push_code.find("bl\t")
    imu_dmb_pos = imu_push_code.find("dmb\tsy")
    imu_head_str = imu_push_code.find("str.w\tr0, [r4, #0x800]")
    assert imu_bl_pos < imu_dmb_pos < imu_head_str
    print("  [PASS] ringbuf_imu_push: memcpy (bl) -> DMB SY -> Head store (str.w [r4, #0x800]) verified")

    # Audit Function 5: ringbuf_imu_pop
