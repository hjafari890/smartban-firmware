# SUITE 1: High-Throughput Multi-Threaded Concurrency Stress Verification
# =============================================================================
def test_concurrency_stress():
    print("\n" + "="*78)
    print(" [CHALLENGE SUITE 1] HIGH-THROUGHPUT MULTI-THREADED CONCURRENCY STRESS")
    print("="*78)

    # -------------------------------------------------------------------------
    # Test 1.1: ECG SPSC Buffer Concurrency (Capacity 128, 50,000 samples)
    # -------------------------------------------------------------------------
    print("  --- Test 1.1: ECG SPSC Concurrency (50,000 samples, random jitter) ---")
    rb_ecg = CModelSPSCRingBuffer(128)
    NUM_SAMPLES = 50000
    consumed_ecg = []
    prod_done = threading.Event()

    def ecg_producer():
        for i in range(NUM_SAMPLES):
            sample = {
                "timestamp_ms": i * 4,
                "ch1_uV": (i % 1000) * 10 - 5000,
                "ch2_uV": -(i % 1000) * 10 + 5000,
                "status": 0xC0,
                "sequence": i
            }
            while not rb_ecg.push(sample):
                # Buffer full: yield with tiny random sleep to test preemption
                if random.random() < 0.05:
                    time.sleep(0.0001)
                else:
                    time.sleep(0)
            if random.random() < 0.01:
                time.sleep(0.00005)
        prod_done.set()

    def ecg_consumer():
        while not (prod_done.is_set() and rb_ecg.is_empty()):
            # Vary consumption strategy: single pop vs batch pop
            mode = random.randint(0, 2)
            if mode == 0:
                s = rb_ecg.pop()
                if s is not None:
                    consumed_ecg.append(s)
            elif mode == 1:
                batch = rb_ecg.pop_batch(random.choice([2, 4, 8, 16, 32]))
                consumed_ecg.extend(batch)
            else:
                # Peek then pop
                peeked = rb_ecg.peek()
                if peeked is not None:
                    popped = rb_ecg.pop()
                    assert popped == peeked, "Peek/Pop mismatch under concurrency"
                    consumed_ecg.append(popped)
            if random.random() < 0.01:
                time.sleep(0.00005)

    t_p = threading.Thread(target=ecg_producer)
    t_c = threading.Thread(target=ecg_consumer)
    t_p.start()
    t_c.start()
    t_p.join(timeout=30.0)
    t_c.join(timeout=30.0)

    assert not t_p.is_alive(), "ECG producer hung under concurrency"
    assert not t_c.is_alive(), "ECG consumer hung under concurrency"
    assert len(consumed_ecg) == NUM_SAMPLES, f"Sample count mismatch: {len(consumed_ecg)} != {NUM_SAMPLES}"

    # Verify bit-for-bit payload integrity and strict monotonicity
    for idx, s in enumerate(consumed_ecg):
        assert s["sequence"] == idx, f"Sequence out of order at index {idx}: expected {idx}, got {s['sequence']}"
        assert s["timestamp_ms"] == idx * 4, f"Corrupted timestamp at index {idx}"
        assert s["ch1_uV"] == (idx % 1000) * 10 - 5000, f"Corrupted ch1 at index {idx}"
        assert s["ch2_uV"] == -(idx % 1000) * 10 + 5000, f"Corrupted ch2 at index {idx}"
        assert s["status"] == 0xC0, f"Corrupted status at index {idx}"

    assert rb_ecg.pushed_count == NUM_SAMPLES
    assert rb_ecg.popped_count == NUM_SAMPLES
    assert rb_ecg.is_empty()
    print(f"  [PASS] ECG SPSC: {NUM_SAMPLES:,} samples transferred concurrently with 0 corruption, 0 lost tokens.")

    # -------------------------------------------------------------------------
    # Test 1.2: IMU SPSC Buffer Concurrency (Capacity 64, 50,000 samples)
    # -------------------------------------------------------------------------
    print("  --- Test 1.2: IMU SPSC Concurrency (50,000 samples, tight capacity 64) ---")
    rb_imu = CModelSPSCRingBuffer(64)
    consumed_imu = []
    prod_imu_done = threading.Event()

    def imu_producer():
        for i in range(NUM_SAMPLES):
            sample = {
                "timestamp_ms": i * 10,
                "x_mg": (i % 200) - 100,
                "y_mg": (i % 300) - 150,
                "z_mg": 980 + (i % 50),
                "total_g": 0.98 + (i % 10) * 0.01,
                "pitch_deg": 12.5,
                "roll_deg": -5.2,
                "temp_c": 24.5,
                "status": 0x41,
                "sequence": i
            }
            while not rb_imu.push(sample):
                time.sleep(0)
            if i % 1000 == 0:
                time.sleep(0.0001)
        prod_imu_done.set()

    def imu_consumer():
        while not (prod_imu_done.is_set() and rb_imu.is_empty()):
            batch = rb_imu.pop_batch(random.choice([1, 3, 7, 15, 31, 63]))
            if batch:
                consumed_imu.extend(batch)
            else:
                time.sleep(0)

    t_p2 = threading.Thread(target=imu_producer)
    t_c2 = threading.Thread(target=imu_consumer)
    t_p2.start()
    t_c2.start()
    t_p2.join(timeout=30.0)
    t_c2.join(timeout=30.0)

    assert not t_p2.is_alive(), "IMU producer hung"
    assert not t_c2.is_alive(), "IMU consumer hung"
    assert len(consumed_imu) == NUM_SAMPLES, f"IMU samples lost: {len(consumed_imu)} != {NUM_SAMPLES}"

    for idx, s in enumerate(consumed_imu):
        assert s["sequence"] == idx, f"IMU sequence mismatch at {idx}: expected {idx}, got {s['sequence']}"
        assert s["timestamp_ms"] == idx * 10
        assert s["x_mg"] == (idx % 200) - 100
        assert s["y_mg"] == (idx % 300) - 150
        assert s["z_mg"] == 980 + (idx % 50)
        assert abs(s["total_g"] - (0.98 + (idx % 10) * 0.01)) < 1e-5

    assert rb_imu.pushed_count == NUM_SAMPLES
    assert rb_imu.popped_count == NUM_SAMPLES
    assert rb_imu.is_empty()
    print(f"  [PASS] IMU SPSC: {NUM_SAMPLES:,} samples transferred with zero loss through 64-slot buffer.")
    print("  [TOTAL CONCURRENT SAMPLES VERIFIED: 100,000 SAMPLES WITH ZERO ERRORS]")


