def uint32(val):
    """32-bit unsigned modulo arithmetic."""
    return val & 0xFFFFFFFF


# =============================================================================
# Behavioral & Bit-Exact C-Model of SPSC Lock-Free Circular Ring Buffer
# =============================================================================
class CModelSPSCRingBuffer:
    """
    Bit-exact simulation of C implementation in ipc/ring_buffer.c:
    - Fixed capacity (power-of-two)
    - Monotonic 32-bit uint32 head and tail
    - Atomic-style head/tail updates
    - Non-overwriting drop policy
    - Full struct statistics tracking
    """
    def __init__(self, capacity):
        assert (capacity & (capacity - 1)) == 0, "Capacity must be power of two"
        self.capacity = capacity
        self.mask = capacity - 1
        self.buffer = [None] * capacity
        self.head = 0
        self.tail = 0
        self.pushed_count = 0
        self.popped_count = 0
        self.dropped_count = 0
        self.peak_utilization = 0

    def reset(self):
        self.head = 0
        self.tail = 0
        self.pushed_count = 0
        self.popped_count = 0
        self.dropped_count = 0
        self.peak_utilization = 0

    def available(self):
        return uint32(self.head - self.tail)

    def count(self):
        return self.available()

    def free_space(self):
        cnt = self.available()
        return (self.capacity - cnt) if cnt < self.capacity else 0

    def is_empty(self):
        return self.head == self.tail

    def is_full(self):
        return self.available() >= self.capacity

    def push(self, sample):
        if sample is None:
            return False

        current_head = self.head
        current_tail = self.tail

        if uint32(current_head - current_tail) >= self.capacity:
            self.dropped_count += 1
            return False

        index = current_head & self.mask
        # Payload copy (simulates buffer[index] = *sample)
        self.buffer[index] = dict(sample) if isinstance(sample, dict) else sample

        # Memory barrier DMB() simulated: write committed before head update
        self.head = uint32(current_head + 1)
        self.pushed_count += 1

        util = uint32(current_head + 1 - current_tail)
        if util > self.peak_utilization:
            self.peak_utilization = util
        return True

    def pop(self):
        current_tail = self.tail
        current_head = self.head

        if current_head == current_tail:
            return None

        index = current_tail & self.mask
        # DMB() ensures head observed before reading payload
        sample = dict(self.buffer[index]) if isinstance(self.buffer[index], dict) else self.buffer[index]

        # DMB() ensures payload read finishes before advancing tail
        self.tail = uint32(current_tail + 1)
        self.popped_count += 1
        return sample

    def peek(self):
        current_tail = self.tail
        current_head = self.head

        if current_head == current_tail:
            return None

        index = current_tail & self.mask
        return dict(self.buffer[index]) if isinstance(self.buffer[index], dict) else self.buffer[index]

    def pop_batch(self, max_count):
        if max_count == 0:
            return []

        current_tail = self.tail
        current_head = self.head
        available = uint32(current_head - current_tail)

        if available == 0:
            return []

        count = min(available, max_count)
        result = []
        for i in range(count):
            index = uint32(current_tail + i) & self.mask
            item = self.buffer[index]
            result.append(dict(item) if isinstance(item, dict) else item)

        # DMB() before advancing tail
        self.tail = uint32(current_tail + count)
        self.popped_count += count
        return result


