# SUITE 3: Overflow Saturation & Drop Counter Invariant Verification
# =============================================================================
def test_overflow_saturation():
    print("\n" + "="*78)
    print(" [CHALLENGE SUITE 3] OVERFLOW SATURATION & DROP COUNTER AUDIT")
    print("="*78)

    # 1. ECG Buffer Saturation (Capacity 128)
    rb_ecg = CModelSPSCRingBuffer(128)
    for i in range(128):
        assert rb_ecg.push({"orig_id": i}), f"Setup push {i} failed"

    assert rb_ecg.is_full()
    assert rb_ecg.free_space() == 0
    assert rb_ecg.available() == 128
    orig_head = rb_ecg.head
    orig_tail = rb_ecg.tail

    # Attempt to push 10,000 extra samples into saturated buffer
    OVERFLOW_ATTEMPTS = 10000
    for i in range(OVERFLOW_ATTEMPTS):
        ok = rb_ecg.push({"dropped_id": 900000 + i})
        assert not ok, f"Over-fill push {i} should have returned False"

    # Verify invariants:
    assert rb_ecg.dropped_count == OVERFLOW_ATTEMPTS, f"Dropped mismatch: {rb_ecg.dropped_count}"
    assert rb_ecg.pushed_count == 128, f"Pushed count altered during overflow: {rb_ecg.pushed_count}"
    assert rb_ecg.head == orig_head, f"Head altered during overflow: {rb_ecg.head} != {orig_head}"
    assert rb_ecg.tail == orig_tail, f"FATAL: Tail corrupted by producer during overflow: {rb_ecg.tail} != {orig_tail}"
    assert rb_ecg.available() == 128
    assert rb_ecg.is_full()
    print(f"  [PASS] ECG Buffer: {OVERFLOW_ATTEMPTS:,} drops recorded, head/tail untouched, integrity preserved")

    # Verify oldest data was NOT overwritten
    for i in range(128):
        item = rb_ecg.pop()
        assert item is not None, f"Pop {i} returned None"
        assert item["orig_id"] == i, f"Oldest data corrupted at slot {i}: expected {i}, got {item.get('orig_id')}"
    assert rb_ecg.is_empty()
    assert rb_ecg.popped_count == 128
    print("  [PASS] Oldest-preserved drop policy confirmed: all 128 original samples intact")

    # 2. IMU Buffer Saturation (Capacity 64)
    rb_imu = CModelSPSCRingBuffer(64)
    for i in range(64):
        assert rb_imu.push({"imu_id": i})

    assert rb_imu.is_full()
    for i in range(5000):
        ok = rb_imu.push({"bad": i})
        assert not ok

    assert rb_imu.dropped_count == 5000
    assert rb_imu.pushed_count == 64
    assert rb_imu.available() == 64

    for i in range(64):
        item = rb_imu.pop()
        assert item["imu_id"] == i
    assert rb_imu.is_empty()
    print("  [PASS] IMU Buffer: 5,000 drops recorded, 64 original samples intact")

    # 3. Interleaved Drops & Recoveries
    rb_ecg.reset()
    for i in range(128):
        rb_ecg.push({"id": i})

    # 5 drops
    for _ in range(5):
        assert not rb_ecg.push({"bad": 1})
    # Pop 1 -> space for 1
    s = rb_ecg.pop()
    assert s["id"] == 0
    assert rb_ecg.free_space() == 1
    # Push 1
    assert rb_ecg.push({"id": 128})
    assert rb_ecg.is_full()
    # 5 more drops
    for _ in range(5):
        assert not rb_ecg.push({"bad": 2})

    assert rb_ecg.dropped_count == 10
    remaining = rb_ecg.pop_batch(200)
    assert len(remaining) == 128
    assert remaining[0]["id"] == 1
    assert remaining[-1]["id"] == 128
    assert rb_ecg.is_empty()
    print("  [PASS] Interleaved saturation & pop recovery verified with exact drop tracking")


